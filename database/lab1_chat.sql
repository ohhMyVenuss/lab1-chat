CREATE DATABASE IF NOT EXISTS ltm_chat CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS 'ltm_app'@'localhost' IDENTIFIED BY 'CHANGE_THIS_PASSWORD';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE ON ltm_chat.* TO 'ltm_app'@'localhost';
FLUSH PRIVILEGES;
USE ltm_chat;
CREATE TABLE IF NOT EXISTS chat_users(username VARCHAR(64) PRIMARY KEY, first_seen TIMESTAMP DEFAULT CURRENT_TIMESTAMP, last_seen TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS chat_messages(id BIGINT AUTO_INCREMENT PRIMARY KEY, sender VARCHAR(64) NOT NULL, recipient VARCHAR(64), chat_type VARCHAR(20) NOT NULL, content TEXT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);

CREATE TABLE IF NOT EXISTS chat_attachments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 sender VARCHAR(64) NOT NULL,
 recipient VARCHAR(64) NULL,
 chat_scope VARCHAR(20) NOT NULL,
 file_name VARCHAR(255) NOT NULL,
 content_type VARCHAR(128) NOT NULL,
 storage_path VARCHAR(1024) NOT NULL,
 size_bytes BIGINT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_chat_attachments_sender (sender),
 INDEX idx_chat_attachments_created (created_at)
);
